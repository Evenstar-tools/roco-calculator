function createStructuredRelease({ sections, ...release }) {
  const normalizeSections = (groups) => {
    const features = groups
      .filter(({ kind }) => kind !== "fix")
      .flatMap(({ items }) => items);
    const fixes = groups
      .filter(({ kind }) => kind === "fix")
      .flatMap(({ items }) => items);

    return [
      ...(features.length
        ? [{ kind: "feature", label: "新增功能", items: features }]
        : []),
      ...(fixes.length
        ? [{ kind: "fix", label: "修复与优化", items: fixes }]
        : []),
    ];
  };
  const normalizedSections = normalizeSections(sections);
  const flatten = (groups) => groups.flatMap(({ items }) => items);

  return Object.freeze({
    ...release,
    highlights: flatten(normalizedSections),
    sections: normalizedSections,
  });
}

function createRelease({ features = [], fixes = [], ...release }) {
  return createStructuredRelease({
    ...release,
    sections: [
      ...(features.length
        ? [{ kind: "feature", label: "新增功能", items: features }]
        : []),
      ...(fixes.length
        ? [{ kind: "fix", label: "修复与优化", items: fixes }]
        : []),
    ],
  });
}

